#!/usr/bin/env python3
"""Scope 3 completion I-08 (Claude, 30 October 2026): write the record forms' register labels module.

The Activity screen's spend form lets the user search and pick a 2017 NAICS-6 code, and the fuel forms name each EPA GHG
Emission Factors Hub 2025 Table 1 fuel and its unit. Both lists come from the verified registers, never typed by hand:
- R2 `verified-scope3-spend-register-epa-scghg-v1.3.json`: one entry per code and margin choice; the code's title is the
  entry `label` (the CSV's "2017 NAICS Title" cell). Each code appears with the same title in both margin entries.
- R3 `verified-scope3-supplement-register-2025.json`: `hub2025_t1.<fuel>.heat_content` gives the fuel's label and the unit
  its heat content is per (mmBtu per gallon / short ton / scf), i.e. the Hub Table 1 unit of the fuel.

Usage: python3 tools/scope3/make_form_labels.py <repo root>
The web test `scope3-forms.test.ts` re-reads both registers and requires the two modules to equal them exactly.
"""
import json
import sys
from pathlib import Path

root = Path(sys.argv[1] if len(sys.argv) > 1 else '.')
reference = root / 'packages/neuvetra-database/src/method-reference'
spend = json.loads((reference / 'verified-scope3-spend-register-epa-scghg-v1.3.json').read_text(encoding='utf-8'))
supplement = json.loads((reference / 'verified-scope3-supplement-register-2025.json').read_text(encoding='utf-8'))

titles = {}
for entry in spend['entries']:
    parts = entry['id'].split('.')
    if len(parts) != 3 or parts[0] != 'epa_scghg_v130':
        continue
    code = parts[1]
    if code in titles and titles[code] != entry['label']:
        raise SystemExit(f'NAICS {code} has two titles')
    titles[code] = entry['label']
if len(titles) != 1016:
    raise SystemExit(f'expected 1,016 NAICS codes, found {len(titles)}')

UNITS = {'mmBtu per gallon (HHV)': 'US_gallon', 'mmBtu per short ton (HHV)': 'short_ton', 'mmBtu per scf (HHV)': 'scf'}
fuels = {}
for entry in supplement['entries']:
    parts = entry['id'].split('.')
    if len(parts) == 3 and parts[0] == 'hub2025_t1' and parts[2] == 'heat_content':
        fuels[parts[1]] = {'label': entry['label'], 'unit': UNITS[entry['unit']]}
if len(fuels) != 58:
    raise SystemExit(f'expected 58 Hub Table 1 fuels, found {len(fuels)}')

def ts(value):
    return json.dumps(value, ensure_ascii=False)

# Round 2 polish (lane D, 31 October 2026; ENG-13 follow-up): the NAICS titles are their own module, imported only by the
# spend form and the spend import (lazy chunks), so the 58 kB list is not in the entry chunk; the sold fuels stay here.
naics_lines = [
    '/**',
    ' * Generated by tools/scope3/make_form_labels.py (Scope 3 completion I-08; do not edit by hand). Browser-safe data only.',
    ' *',
    ' * `SCOPE3_NAICS_TITLES`: the 1,016 2017 NAICS-6 codes of the EPA Supply Chain GHG Emission Factors v1.3.0 and their',
    ' * titles, as the verified spend register (R2) records them (entry `label`, the CSV\'s "2017 NAICS Title" cell).',
    ' * Its own module (round 2): only the spend form and the spend import import it, so it loads with their chunks.',
    ' * A web test compares it with the register, so the module cannot drift from it.',
    ' */',
    f'export const SCOPE3_NAICS_TITLES: Readonly<Record<string, string>> = {{',
]
for code in sorted(titles):
    naics_lines.append(f"  '{code}': {ts(titles[code])},")
naics_lines.append('}')
lines = [
    '/**',
    ' * Generated by tools/scope3/make_form_labels.py (Scope 3 completion I-08; do not edit by hand). Browser-safe data only.',
    ' *',
    ' * `SCOPE3_SOLD_FUEL_FACTS`: each EPA GHG Emission Factors Hub 2025 Table 1 fuel, its label and the unit its default heat',
    ' * content is per (R3 `hub2025_t1.<fuel>.heat_content`): the unit a fuel sold is recorded in, besides MMBtu.',
    ' * The NAICS titles are in `scope3-naics-titles.ts` (round 2: loaded with the spend chunks only).',
    ' * A web test compares both with the registers, so the modules cannot drift from them.',
    ' */',
]
lines.append(f"export const SCOPE3_SOLD_FUEL_FACTS: Readonly<Record<string, {{ label: string; unit: 'US_gallon' | 'short_ton' | 'scf' }}>> = {{")
for fuel in sorted(fuels):
    lines.append(f"  {fuel}: {{ label: {ts(fuels[fuel]['label'])}, unit: '{fuels[fuel]['unit']}' }},")
lines.append('}')
lib = root / 'apps/site-web/src/lib'
(lib / 'scope3-naics-titles.ts').write_text('\n'.join(naics_lines) + '\n', encoding='utf-8')
out = lib / 'scope3-register-labels.ts'
out.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'wrote {lib / "scope3-naics-titles.ts"} ({len(titles)} NAICS titles) and {out} ({len(fuels)} fuels)')
